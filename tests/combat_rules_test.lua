return function(R)
    local checks=0
    local function check(value,label) checks=checks+1;assert(value,label) end
    local human=R.newPlayer(1,'human');local machine=R.newPlayer(2,'terminator')
    check(human.health==100 and machine.health==1000,'faction health')
    check(R.request(human,'fire',1),'first shot')
    check(human.ammo==29,'server deducts ammo')
    check(not R.request(human,'fire',1.01),'rapid fire rejected')
    check(human.ammo==29,'rejected fire consumes no ammo')
    check(not R.request(human,'give-health',2),'unknown action rejected')
    check(not R.request(human,'fire',0/0),'invalid clock rejected')
    check(R.request(human,'reload',2),'reload starts')
    check(not R.request(human,'fire',3),'no firing during reload')
    check(R.advance(human,3.99)==nil and human.ammo==29,'reload cannot finish early')
    check(R.advance(human,4)=='reloaded' and human.ammo==30 and human.reserve==119,'reload conserves ammunition')
    check(not R.request(human,'reload',5),'full magazine rejects reload')
    check(not R.damagePlayer(machine,human,'coop',5) and human.health==100,'co-op friendly fire blocked')
    check(not R.damagePlayer(human,human,'pvp',5),'self damage blocked')
    for i=1,4 do R.damagePlayer(machine,human,'pvp',5) end
    check(human.health==0 and human.deaths==1 and machine.kills==1,'host applies death once')
    check(not R.damagePlayer(machine,human,'pvp',6) and machine.kills==1,'dead target cannot award more kills')
    check(not R.request(human,'fire',6),'dead player cannot shoot')
    check(R.advance(human,9.99)==nil,'respawn cannot finish early')
    check(R.advance(human,10)=='respawn' and human.health==100 and human.ammo==30,'respawn restores state')
    check(not R.request(human,'fire',10.1),'respawn fire grace interval')
    local wire=R.encode('pvp',1,{human,machine},10)
    local decoded=R.decode(wire)
    check(decoded and decoded.you==1 and #decoded.players==2,'snapshot round trip')
    check(not R.decode(wire..';1,human,100,100,30,120,0,0,0,0'),'duplicate identities rejected')
    check(not R.decode(wire:gsub('30,120','9999,120')),'forged ammo rejected')
    check(not R.decode('TRMP1|S|pvp|3|1,human,100,100,30,120,0,0,0,0'),'missing owner rejected')
    check(not R.decode(string.rep('x',2049)),'oversized payload rejected')
    check(not R.decode('TRMP1|S|pvp|1|1,human,101,100,30,120,0,0,0,0'),'health overflow rejected')
    local o,d,c={X=0,Y=0,Z=0},{X=1,Y=0,Z=0},{X=100,Y=0,Z=0}
    check(math.abs(R.rayCapsule(o,d,c,20,80,500)-80)<0.001,'capsule side hit')
    check(R.rayCapsule(o,d,c,20,80,79)==nil,'obstruction before target blocks hit')
    check(R.rayCapsule(o,{X=0,Y=1,Z=0},c,20,80,500)==nil,'off-axis miss')
    check(math.abs(R.rayCapsule({X=100,Y=0,Z=200},{X=0,Y=0,Z=-1},c,20,80,500)-120)<0.001,'vertical cap hit')
    check(R.rayCapsule(o,{X=10,Y=0,Z=0},c,20,80,500)==nil,'non-unit aim rejected')
    check(R.rayCapsule({X=0/0,Y=0,Z=0},d,c,20,80,500)==nil,'NaN aim rejected')
    return checks
end
