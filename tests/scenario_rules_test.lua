return function(S,R)
    local n=0
    local function check(v,label) n=n+1;assert(v,label) end
    local function pair() return {R.newPlayer(10,'human'),R.newPlayer(20,'terminator')} end
    check(S.faction('BlueprintGeneratedClass /Game/CH_FPPInfiltrator.CH_FPPInfiltrator_C','infiltrator_hunt')=='terminator','native host is machine')
    check(S.faction('Class /Script/Engine.Character','infiltrator_hunt')=='human','remote is defender')
    check(S.faction('Class /Script/Engine.Character','arena')=='terminator','legacy arena roles unchanged')
    check(not S.faction('Class /Game/CH_FPPCharacter','infiltrator_hunt'),'wrong campaign pawn rejected')
    local p=pair();local round=S.new()
    check(not S.step(round,{p[1]},5) and round.phase=='waiting','cannot start alone')
    check(not S.step(round,{p[1],p[1]},5),'same faction cannot start')
    check(S.step(round,p,10) and round.phase=='active','both factions start round')
    check(not S.step(round,p,609.9) and round.seconds==1,'timer does not expire early')
    check(S.step(round,p,610) and round.winner=='human' and round.reason=='survived','surviving defender wins')
    p[1].health=0;S.step(round,p,611)
    check(round.winner=='human','finished result is immutable')
    p=pair();round=S.new();S.step(round,p,0);p[1].health=0;S.step(round,p,1)
    check(round.winner=='terminator' and round.reason=='eliminated','machine wins by eliminating defender')
    p=pair();round=S.new();S.step(round,p,0);p[2].allowRespawn=false
    check(R.hurt(p[2],1000,1),'native NPC damage can eliminate machine')
    S.step(round,p,1)
    check(round.winner=='human','defender wins when NPCs destroy machine')
    check(p[2].deaths==1 and p[2].respawnAt==0 and not R.advance(p[2],100),'one-life actors do not respawn')
    check(not R.hurt(p[2],1,2) and p[2].deaths==1,'duplicate NPC death ignored')
    check(not R.hurt(p[1],0/0,1) and not R.hurt(p[1],10001,1),'invalid native damage bounded')
    p=pair();round=S.new();S.step(round,p,0);S.step(round,{p[1]},1)
    check(round.winner=='human' and round.reason=='disconnected','disconnect forfeits active round')
    p=pair();round=S.new();S.step(round,p,0);p[1].health=0;p[2].health=0;S.step(round,p,1)
    check(round.winner=='none' and round.reason=='draw','simultaneous elimination draws')
    local decoded=S.decode(S.encode(round))
    check(decoded and decoded.phase=='finished' and decoded.reason=='draw','round snapshot roundtrip')
    check(not S.decode('TRMP1|H|active|human|hunt|600|5'),'active snapshot cannot declare winner')
    check(not S.decode('TRMP1|H|active|none|execute|600|5'),'unknown reason rejected')
    check(not S.decode('TRMP1|H|active|none|hunt|601|5'),'timer overflow rejected')
    check(not S.decode('TRMP1|H|active|none|hunt|600|999999'),'NPC overflow rejected')
    check(not S.decode(string.rep('a',161)),'oversized round message rejected')
    return n
end
